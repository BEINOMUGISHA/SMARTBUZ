/**
 * i18n-merge — merge authored translation batches into the dictionaries.
 *
 * A batch file is a JSON object: { "<English source text>": "<translation>" }.
 * A combined batch file is { "sw": {...}, "lg": {...}, "fr": {...} }.
 * Place it in scripts/i18n-batches/ and run:
 *
 *   node scripts/i18n-merge.mjs
 *
 * The script merges every batch into the matching dictionary file
 * (src/i18n/dictionaries/<lang>.ts), replacing an existing key if present,
 * and reports how many keys each language now holds.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const DICT_DIR = path.join(ROOT, "src", "i18n", "dictionaries");
const BATCH_DIR = path.join(ROOT, "scripts", "i18n-batches");

const LANGS = ["sw", "lg", "fr"];

const escapeKey = (s) => JSON.stringify(s);
const escapeValue = (s) => JSON.stringify(s);

/** Read the existing dictionary file into an ordered Map. */
function readDict(lang) {
  const file = path.join(DICT_DIR, `${lang}.ts`);
  const src = fs.readFileSync(file, "utf8");
  const re = /^\s{4}("(?:[^"\\]|\\.)*"):\s*("(?:[^"\\]|\\.)*"),?\s*$/gm;
  const map = new Map();
  let m;
  while ((m = re.exec(src))) {
    map.set(JSON.parse(m[1]), JSON.parse(m[2]));
  }
  return map;
}

function writeDict(lang, map, header) {
  const file = path.join(DICT_DIR, `${lang}.ts`);
  const body = [...map.entries()]
    .map(([k, v]) => `    ${escapeKey(k)}: ${escapeValue(v)},`)
    .join("\n");
  fs.writeFileSync(file, `${header}\n${body}\n};\n`, "utf8");
}

const HEADERS = {
  sw: `/**
 * SMART_BUZ — the Kiswahili words.
 *
 * Keyed by the English, valued in Kiswahili. The catalogue is generated by
 * \`npm run i18n:codemod\`; this file is written by hand, a language at a
 * time, and checked by \`npm run i18n:check\`.
 *
 * Kiswahili is the language of the shop floor and the counter, so the words
 * here are the ones a person says out loud: hana, inafika, onyesha.
 */

/** Every word the product uses, translated into Kiswahili. */
export const sw: Record<string, string> = {`,
  lg: `/**
 * SMART_BUZ — the Luganda words.
 *
 * Keyed by the English, valued in Luganda. The catalogue is generated by
 * \`npm run i18n:codemod\`; this file is written by hand, a language at a
 * time, and checked by \`npm run i18n:check\`.
 *
 * Luganda is the language of the counter in Kampala, so the words here are
 * the ones a person says out loud: teba, gyeyo, nna.
 */

/** Every word the product uses, translated into Luganda. */
export const lg: Record<string, string> = {`,
  fr: `/**
 * SMART_BUZ — the French words.
 *
 * Keyed by the English, valued in French. The catalogue is generated by
 * \`npm run i18n:codemod\`; this file is written by hand, a language at a
 * time, and checked by \`npm run i18n:check\`.
 *
 * French is the language of the regional office, so the words here are the
 * formal ones: vente, stock, facture.
 */

/** Every word the product uses, translated into French. */
export const fr: Record<string, string> = {`,
};

if (!fs.existsSync(BATCH_DIR)) {
  console.error(`No batch directory at ${BATCH_DIR}`);
  process.exit(1);
}

const dicts = Object.fromEntries(LANGS.map((l) => [l, readDict(l)]));
const applied = Object.fromEntries(LANGS.map((l) => [l, 0]));

/*
 * Prune first: a word the product no longer uses is a word nobody should
 * have to translate. The English catalogue is the master list, so a key that
 * is not in it is dead — unless a batch below puts it back, because the
 * catalogue and the screens are read by two different walks and a word can
 * be in one and not the other.
 */
const catalogue = readDict("en");
for (const lang of LANGS) {
    const dead = [];
    for (const key of dicts[lang].keys()) {
        if (!catalogue.has(key)) dead.push(key);
    }
    for (const key of dead) dicts[lang].delete(key);
    console.log(`${lang}: pruned ${dead.length} unused word(s)`);
    for (const key of dead) console.log(`   - ${JSON.stringify(key)}`);
}

for (const file of fs.readdirSync(BATCH_DIR).sort()) {
  if (!file.endsWith(".json")) continue;
  const batch = JSON.parse(fs.readFileSync(path.join(BATCH_DIR, file), "utf8"));

  // Combined form: { "sw": {...}, "lg": {...}, "fr": {...} }
  const combined = Object.keys(batch).some((k) => LANGS.includes(k));
  if (combined) {
    for (const lang of LANGS) {
      const entries = batch[lang];
      if (!entries) continue;
      for (const [k, v] of Object.entries(entries)) {
        dicts[lang].set(k, v);
        applied[lang] += 1;
      }
    }
    console.log(
      `applied ${file} (${LANGS.map((l) => (batch[l] ? `${l}:${Object.keys(batch[l]).length}` : null)).filter(Boolean).join(" ")})`,
    );
    continue;
  }

  // Per-language form: { "<English>": "<translation>" }
  const fileLang = file.split("-")[0];
  if (!LANGS.includes(fileLang)) {
    console.warn(`skipping ${file} (unknown language prefix)`);
    continue;
  }
  for (const [k, v] of Object.entries(batch)) {
    dicts[fileLang].set(k, v);
    applied[fileLang] += 1;
  }
  console.log(`applied ${file} (${Object.keys(batch).length} entries)`);
}

for (const lang of LANGS) {
  writeDict(lang, dicts[lang], HEADERS[lang]);
  console.log(`${lang}: ${dicts[lang].size} entries (${applied[lang]} applied this run)`);
}
